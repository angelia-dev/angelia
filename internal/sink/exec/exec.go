// Package exec is the "exec" sink (ADR 0042, spec ExecSinkConfig,
// docs/exec.md): it runs a command the operator defined in angelia.yaml
// (exec.commands.<name>) once per delivery, with the rendered message on
// stdin.
//
// A sink's configuration only names a command: {"command": "<name>"}. The
// command line, its directory, the variables it may read, its timeout and
// its concurrency come from the instance configuration, never from the
// sink, so no API caller can choose what runs.
//
// The command is started directly (argv, no shell, no placeholders) in its
// own process group, with a clean environment: PATH, the variables named
// in its env list, and six ANGELIA_* identifiers generated by Angelia.
// Nothing from the event is put into its arguments or environment. On
// timeout or cancellation the group gets SIGTERM, then SIGKILL after
// KillGrace. stdout and stderr are each kept to MaxOutput bytes; output
// never reaches an error (delivery.last_error), and only the last
// MaxLoggedStderr bytes of stderr are logged, at warn, on failure.
//
// Linux and macOS only: on other platforms New fails.
package exec

import (
	"bytes"
	"context"
	"encoding/json"
	"errors"
	"fmt"
	"io"
	"log/slog"
	"os"
	osexec "os/exec"
	"path/filepath"
	"runtime"
	"slices"
	"strconv"
	"strings"
	"sync"
	"sync/atomic"
	"time"

	"github.com/angelia-dev/angelia/internal/sink"
)

// Kind is the registry key of this sink.
const Kind = "exec"

// Defaults and bounds of a command (ADR 0042 §4).
const (
	DefaultTimeout = 10 * time.Second
	MinTimeout     = time.Second
	// MaxTimeout is the dispatcher's 15 s attempt budget minus KillGrace
	// and a margin.
	MaxTimeout = 12 * time.Second
	// KillGrace is the time between SIGTERM and SIGKILL to the process
	// group. The command never runs past the attempt's deadline minus it.
	KillGrace = 2 * time.Second

	DefaultMaxConcurrent = 1
	MaxMaxConcurrent     = 8
	// MaxArgs bounds argv.
	MaxArgs = 64

	// MaxOutput is how much of stdout and of stderr is kept, each; the
	// rest is read and discarded.
	MaxOutput = 64 << 10
	// MaxLoggedStderr is how much of the end of stderr a failure logs.
	MaxLoggedStderr = 1 << 10

	// Path is the PATH of every command.
	Path = "/usr/local/bin:/usr/bin:/bin"
)

// The variables Angelia sets for every command, with values it generated.
const (
	EnvEventID        = "ANGELIA_EVENT_ID"
	EnvEventType      = "ANGELIA_EVENT_TYPE"
	EnvDeliveryID     = "ANGELIA_DELIVERY_ID"
	EnvIdempotencyKey = "ANGELIA_IDEMPOTENCY_KEY"
	EnvAttempt        = "ANGELIA_ATTEMPT"
	EnvContentType    = "ANGELIA_CONTENT_TYPE"
)

// Command is one command of exec.commands, checked by internal/config.
type Command struct {
	// Argv is the command line; Argv[0] is an absolute path.
	Argv []string
	// Dir is the working directory; empty means "/".
	Dir string
	// Env names variables copied from Angelia's environment when set.
	Env []string
	// Timeout bounds one run; 0 means DefaultTimeout.
	Timeout time.Duration
	// MaxConcurrent bounds the runs at the same time, across every sink
	// naming the command; 0 means DefaultMaxConcurrent.
	MaxConcurrent int
}

// Options configures a Sink.
type Options struct {
	// Commands are the commands sinks may name, by name. At least one.
	Commands map[string]Command
	// Logger receives the warning of a failed run; nil discards.
	Logger *slog.Logger
	// LookupEnv reads Angelia's environment for the names of Command.Env.
	// Nil means os.LookupEnv.
	LookupEnv func(string) (string, bool)
}

// Config is the configuration of an exec sink (spec ExecSinkConfig).
type Config struct {
	Command string `json:"command"`
}

type command struct {
	Command
	name string
	sem  chan struct{}
}

// Sink is the exec sink. It is safe for concurrent use.
type Sink struct {
	cmds   map[string]*command
	log    *slog.Logger
	lookup func(string) (string, bool)
}

var _ sink.Sink = (*Sink)(nil)

// New returns an exec sink running opts.Commands. It fails on a platform
// without exec support, without commands, or with a command whose argv
// is empty or whose argv[0] is not an absolute path. It does no I/O: the
// start-up check of each argv[0] is CheckCommand.
func New(opts Options) (*Sink, error) {
	if err := supported(); err != nil {
		return nil, err
	}
	if len(opts.Commands) == 0 {
		return nil, errors.New("exec: no command defined")
	}
	s := &Sink{cmds: make(map[string]*command, len(opts.Commands)), log: opts.Logger, lookup: opts.LookupEnv}
	if s.log == nil {
		s.log = slog.New(slog.DiscardHandler)
	}
	if s.lookup == nil {
		s.lookup = os.LookupEnv
	}
	for name, c := range opts.Commands {
		switch {
		case len(c.Argv) == 0 || len(c.Argv) > MaxArgs:
			return nil, fmt.Errorf("exec: command %s: argv must have 1 to %d entries", name, MaxArgs)
		case !filepath.IsAbs(c.Argv[0]):
			return nil, fmt.Errorf("exec: command %s: argv[0] must be an absolute path", name)
		case c.Timeout != 0 && (c.Timeout < MinTimeout || c.Timeout > MaxTimeout):
			return nil, fmt.Errorf("exec: command %s: timeout must be from %v to %v", name, MinTimeout, MaxTimeout)
		case c.MaxConcurrent < 0 || c.MaxConcurrent > MaxMaxConcurrent:
			return nil, fmt.Errorf("exec: command %s: max_concurrent must be from 1 to %d", name, MaxMaxConcurrent)
		}
		if c.Timeout == 0 {
			c.Timeout = DefaultTimeout
		}
		if c.MaxConcurrent == 0 {
			c.MaxConcurrent = DefaultMaxConcurrent
		}
		if c.Dir == "" {
			c.Dir = "/"
		}
		c.Argv, c.Env = slices.Clone(c.Argv), slices.Clone(c.Env)
		s.cmds[name] = &command{Command: c, name: name, sem: make(chan struct{}, c.MaxConcurrent)}
	}
	return s, nil
}

// CheckCommand checks that argv0 exists, is a regular file and is
// executable by someone: the start-up check of serve and config check.
func CheckCommand(argv0 string) error {
	fi, err := os.Stat(argv0)
	switch {
	case err != nil:
		return fmt.Errorf("%s: %w", argv0, errors.Unwrap(err))
	case !fi.Mode().IsRegular():
		return fmt.Errorf("%s: not a regular file", argv0)
	case fi.Mode().Perm()&0o111 == 0:
		return fmt.Errorf("%s: not executable", argv0)
	}
	return nil
}

var errTimedOut = errors.New("exec: command timed out")

// Kind implements sink.Sink.
func (*Sink) Kind() string { return Kind }

// Validate implements sink.Sink: the configuration names a configured
// command and has no other key. It does no I/O.
func (s *Sink) Validate(cfg sink.Config) error {
	_, err := s.command(cfg)
	return err
}

// undefinedError is a configuration that names a command this process
// does not define: retried at delivery, since the fix (defining it on
// this dispatcher node and restarting) needs no change to the sink.
type undefinedError struct{ name string }

func (e undefinedError) Error() string {
	return fmt.Sprintf("exec: command %q is not defined under exec.commands in angelia.yaml", e.name)
}

func (s *Sink) command(cfg sink.Config) (*command, error) {
	var c Config
	dec := json.NewDecoder(bytes.NewReader(cfg))
	dec.DisallowUnknownFields()
	if err := dec.Decode(&c); err != nil {
		return nil, fmt.Errorf("exec: invalid configuration: %w", err)
	}
	if dec.More() {
		return nil, errors.New("exec: invalid configuration: trailing data")
	}
	if c.Command == "" {
		return nil, errors.New("exec: command is required: the name of a command under exec.commands in angelia.yaml")
	}
	cmd, ok := s.cmds[c.Command]
	if !ok {
		return nil, undefinedError{c.Command}
	}
	return cmd, nil
}

// Deliver implements sink.Sink: one run of the command. Exit status 0 is
// delivered; any other exit, a signal, a timeout or a cancellation is
// retried; a command that cannot be started is permanent. A malformed
// configuration is permanent; one naming a command this process does not
// define is retried (every dispatcher node must define every command).
func (s *Sink) Deliver(ctx context.Context, req sink.Request) (sink.Result, error) {
	c, err := s.command(req.Config)
	if err != nil {
		if errors.As(err, new(undefinedError)) {
			return sink.Result{}, err
		}
		return sink.Result{}, sink.Permanent(err)
	}
	select {
	case c.sem <- struct{}{}:
	case <-ctx.Done():
		return sink.Result{}, fmt.Errorf("exec %s: canceled while waiting for a free slot (max_concurrent %d): %w", c.name, c.MaxConcurrent, ctx.Err())
	}
	defer func() { <-c.sem }()

	timeout := c.Timeout
	if dl, ok := ctx.Deadline(); ok {
		timeout = min(timeout, time.Until(dl)-KillGrace)
	}
	if timeout < MinTimeout {
		return sink.Result{}, fmt.Errorf("exec %s: less than %v left in the attempt; not started", c.name, MinTimeout)
	}
	runCtx, cancel := context.WithTimeoutCause(ctx, timeout, errTimedOut)
	defer cancel()

	stdout, stderr := newTail(MaxOutput), newTail(MaxOutput)
	cmd := osexec.CommandContext(runCtx, c.Argv[0], c.Argv[1:]...) //nolint:gosec // ADR 0042 D100/D101: argv comes only from angelia.yaml
	cmd.Dir = c.Dir
	cmd.Env = s.environ(c, req)
	cmd.Stdin = bytes.NewReader(req.Rendered.Body)
	cmd.Stdout, cmd.Stderr = stdout, stderr
	cmd.WaitDelay = KillGrace
	st := &runState{}
	prepare(cmd, st)

	waitErr, err := run(cmd, st)
	if err != nil {
		if ctx.Err() != nil {
			return sink.Result{}, fmt.Errorf("exec %s: canceled: %w", c.name, ctx.Err())
		}
		return sink.Result{}, startError(c.name, err)
	}
	failure := outcome(c.name, timeout, waitErr, st.fired.Load(), context.Cause(runCtx), ctx.Err())
	if failure == nil {
		return sink.Result{StatusCode: 0}, nil
	}
	s.log.Warn("exec sink: command failed", "command", c.name, "sink_id", req.SinkID,
		"delivery_id", req.DeliveryID, "attempt", req.Attempt, "error", failure.Error(),
		"stderr", strings.ToValidUTF8(string(lastBytes(stderr.Bytes(), MaxLoggedStderr)), "�"))
	return sink.Result{}, failure
}

// run starts cmd and waits for it, on one locked OS thread from start to
// end: Linux sends the child's Pdeathsig when the thread that started it
// exits, so the thread must outlive the child. Once the leader has exited,
// whatever is left of its process group (a background child, a grandchild
// holding a pipe) is killed with SIGKILL, whatever the exit status: on
// Linux before the leader is reaped, so the group id cannot be reused in
// between; elsewhere just after. startErr is the error of Start.
func run(cmd *osexec.Cmd, st *runState) (waitErr, startErr error) {
	runtime.LockOSThread()
	defer runtime.UnlockOSThread()
	if err := cmd.Start(); err != nil {
		return nil, err
	}
	early := killGroupAtExit(cmd)
	if early {
		st.stopKill()
	}
	waitErr = cmd.Wait()
	if !early {
		st.stopKill()
		killGroup(cmd)
	}
	return waitErr, nil
}

// runState is what the Cancel func of one run records.
type runState struct {
	// fired is set when Cancel signalled the group: the run was cut by
	// its timeout or by the context, whatever its exit status.
	fired   atomic.Bool
	mu      sync.Mutex
	kill    *time.Timer
	stopped bool
}

// armKill schedules f (SIGKILL to the group) after KillGrace.
func (r *runState) armKill(f func()) {
	r.mu.Lock()
	defer r.mu.Unlock()
	if !r.stopped {
		r.kill = time.AfterFunc(KillGrace, f)
	}
}

// stopKill cancels the scheduled SIGKILL, and any later one, once the
// leader has exited: run then kills the group itself.
func (r *runState) stopKill() {
	r.mu.Lock()
	defer r.mu.Unlock()
	r.stopped = true
	if r.kill != nil {
		r.kill.Stop()
	}
}

// outcome classifies a finished run. A run whose Cancel never fired is
// judged by its exit status alone, even when the deadline passed while it
// was ending; one that Cancel interrupted is a timeout when cause is the
// command's own timeout, else a cancellation (shutdown, lease end).
func outcome(name string, timeout time.Duration, waitErr error, fired bool, cause, parentErr error) error {
	switch {
	case !fired && (waitErr == nil || errors.Is(waitErr, osexec.ErrWaitDelay)):
		// Exit 0; a descendant that kept stdout or stderr open past
		// KillGrace does not change the outcome.
		return nil
	case !fired:
		return exitError(name, waitErr)
	case errors.Is(cause, errTimedOut):
		// The attempt's deadline may have passed too during KillGrace.
		return fmt.Errorf("exec %s: timed out after %v", name, timeout.Round(time.Millisecond))
	default:
		if parentErr == nil {
			parentErr = cause
		}
		return fmt.Errorf("exec %s: canceled: %w", name, parentErr)
	}
}

// environ is the child's whole environment (ADR 0042 §3).
func (s *Sink) environ(c *command, req sink.Request) []string {
	env := []string{"PATH=" + Path}
	for _, name := range c.Env {
		if strings.HasPrefix(name, "ANGELIA_") {
			continue // refused by internal/config; never copied
		}
		v, ok := s.lookup(name)
		if !ok {
			continue
		}
		if name == "PATH" {
			env[0] = "PATH=" + v
			continue
		}
		env = append(env, name+"="+v)
	}
	return append(env,
		EnvEventID+"="+req.Event.Envelope.ID,
		EnvEventType+"="+req.Event.Envelope.Type,
		EnvDeliveryID+"="+req.DeliveryID,
		EnvIdempotencyKey+"="+req.IdempotencyKey,
		EnvAttempt+"="+strconv.FormatInt(req.Attempt, 10),
		EnvContentType+"="+req.Rendered.ContentType,
	)
}

// tail is an io.Writer that keeps the last max bytes written to it and
// discards the rest; it never holds more than max bytes.
type tail struct {
	buf []byte
	max int
	n   int64
}

func newTail(maxLen int) *tail { return &tail{max: maxLen} }

func (t *tail) Write(p []byte) (int, error) {
	t.n += int64(len(p))
	if t.buf == nil {
		t.buf = make([]byte, 0, t.max)
	}
	if len(p) >= t.max {
		t.buf = append(t.buf[:0], p[len(p)-t.max:]...)
		return len(p), nil
	}
	if drop := len(t.buf) + len(p) - t.max; drop > 0 {
		t.buf = t.buf[:copy(t.buf, t.buf[drop:])]
	}
	t.buf = append(t.buf, p...)
	return len(p), nil
}

// Bytes returns the bytes kept.
func (t *tail) Bytes() []byte { return t.buf }

var _ io.Writer = (*tail)(nil)

func lastBytes(b []byte, n int) []byte {
	if len(b) > n {
		return b[len(b)-n:]
	}
	return b
}
