package api

import (
	"os"
	"strings"
	"testing"
)

// The template override is a copy of one oapi-codegen release's template:
// the go:generate line, the generated code and oapiCodegenVersion must name
// the same release, so an upgrade cannot skip the re-diff (ADR 0022).
func TestGeneratorPinned(t *testing.T) {
	gen, err := os.ReadFile("generate.go")
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(gen), "cmd/oapi-codegen@"+oapiCodegenVersion+" ") {
		t.Errorf("generate.go does not run oapi-codegen %s", oapiCodegenVersion)
	}
	code, err := os.ReadFile("api.gen.go")
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(code), "oapi-codegen/v2 version "+oapiCodegenVersion+" DO NOT EDIT") {
		t.Errorf("api.gen.go was not generated by oapi-codegen %s", oapiCodegenVersion)
	}
	tmpl, err := os.ReadFile("strict-interface.tmpl")
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(tmpl), "oapi-codegen "+oapiCodegenVersion+"'s strict/strict-interface.tmpl") {
		t.Errorf("strict-interface.tmpl does not say it copies the %s template", oapiCodegenVersion)
	}
}
