package apiclient

import (
	"os"
	"strings"
	"testing"
)

// The go:generate line, the generated code and oapiCodegenVersion name one
// oapi-codegen release, so an upgrade cannot update only one of them.
func TestGeneratorPinned(t *testing.T) {
	gen, err := os.ReadFile("generate.go")
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(gen), "cmd/oapi-codegen@"+oapiCodegenVersion+" ") {
		t.Errorf("generate.go does not run oapi-codegen %s", oapiCodegenVersion)
	}
	code, err := os.ReadFile("client.gen.go")
	if err != nil {
		t.Fatal(err)
	}
	if !strings.Contains(string(code), "oapi-codegen/v2 version "+oapiCodegenVersion+" DO NOT EDIT") {
		t.Errorf("client.gen.go was not generated by oapi-codegen %s", oapiCodegenVersion)
	}
}
