// runCLIIn is runCLI with stdin.
func runCLIIn(t *testing.T, stdin string, args ...string) (stdout, stderr string, err error) {
	t.Helper()
	root := newRootCmd()
	var o, e bytes.Buffer
	root.SetIn(strings.NewReader(stdin))
	root.SetOut(&o)
	root.SetErr(&e)
	root.SetArgs(args)
	err = root.ExecuteContext(t.Context())
	return o.String(), e.String(), err
}

func importWrite(t *testing.T, dir, name, content string) string {
	t.Helper()
	p := filepath.Join(dir, name)
	if err := os.MkdirAll(filepath.Dir(p), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(p, []byte(content), 0o644); err != nil { //nolint:gosec // test data
		t.Fatal(err)
	}
	return p
}

func mustImport(t *testing.T, args ...string) string {
	t.Helper()
	out, errOut, err := runCLI(t, append([]string{"import"}, args...)...)
	if err != nil {
		t.Fatalf("import %v: %v\nstderr: %s", args, err, errOut)
	}
	return out
}

// Criterion (98-A): import | apply --prune -l: one created, one deleted, the
// rest unchanged; a third identical run changes nothing.
func TestImportApplyEndToEnd(t *testing.T) {
	a := newApplyEnv(t)
	dir := t.TempDir()
	req := importWrite(t, dir, "requirements.txt", "requests==2.31.0\nflask>=2\nsix\n")
	sh := func(args ...string) string {
		t.Helper()
		yaml := mustImport(t, append([]string{req}, args...)...)
		out, errOut, err := runCLIIn(t, yaml, append([]string{"apply", "-f", "-", "--prune", "-l", "project=api"}, a.conn...)...)
		if err != nil {
			t.Fatalf("apply: %v\n%s\n%s", err, out, errOut)
		}
		return out
	}
	out := sh("--project", "api")
	if got, want := summary(out), "3 created, 0 updated, 0 unchanged, 0 deleted"; got != want {
		t.Fatalf("first: %q, want %q\n%s", got, want, out)
	}
	if got := strings.Join(a.names("watch"), " "); got != "api-pypi-flask api-pypi-requests api-pypi-six" {
		t.Errorf("watches: %s", got)
	}

	importWrite(t, dir, "requirements.txt", "requests==2.31.0\nflask>=2\nDjango\n")
	out = sh("--project", "api")
	if got, want := summary(out), "1 created, 0 updated, 2 unchanged, 1 deleted"; got != want {
		t.Fatalf("second: %q, want %q\n%s", got, want, out)
	}
	for _, line := range []string{"watch/api-pypi-django created", "watch/api-pypi-six deleted", "watch/api-pypi-flask unchanged"} {
		if !strings.Contains(out, line) {
			t.Errorf("missing %q in\n%s", line, out)
		}
	}
	out = sh("--project", "api")
	if got, want := summary(out), "0 created, 0 updated, 3 unchanged, 0 deleted"; got != want {
		t.Fatalf("third: %q, want %q\n%s", got, want, out)
	}
}

// Criterion: the pipe works with -l owner labels and a subscription on an
// existing sink; apply reports the subscription as created.
func TestImportSubscribeThroughApply(t *testing.T) {
	a := newApplyEnv(t)
	dir := t.TempDir()
	sink := importWrite(t, dir, "sink.yaml", "version: 1\nsinks:\n  - {name: ci, kind: webhook, config: {url: \"https://ci.example.org/hook\"}}\n")
	a.must("apply", "-f", sink)
	req := importWrite(t, dir, "requirements.txt", "requests\n")
	yaml := mustImport(t, req, "--project", "api", "-l", "team=platform", "--subscribe", "ci", "--interval", "6h")
	out, errOut, err := runCLIIn(t, yaml, append([]string{"apply", "-f", "-", "--prune", "-l", "team=platform"}, a.conn...)...)
	if err != nil {
		t.Fatalf("apply: %v\n%s\n%s", err, out, errOut)
	}
	if got, want := summary(out), "2 created, 0 updated, 0 unchanged, 0 deleted"; got != want {
		t.Errorf("%q, want %q\n%s", got, want, out)
	}
	if got := strings.Join(a.names("sub"), " "); got != "api-deps" {
		t.Errorf("subscriptions: %s", got)
	}
}

type failingTransport struct{ t *testing.T }

func (f failingTransport) RoundTrip(r *http.Request) (*http.Response, error) {
	f.t.Errorf("network request to %s", r.URL)
	return nil, errors.New("no network in import")
}

// Criterion: no network.
func TestImportMakesNoRequest(t *testing.T) {
	isolate(t)
	t.Setenv("HTTP_PROXY", "http://127.0.0.1:1")
	t.Setenv("HTTPS_PROXY", "http://127.0.0.1:1")
	old := http.DefaultTransport
	http.DefaultTransport = failingTransport{t}
	t.Cleanup(func() { http.DefaultTransport = old })
	dir := t.TempDir()
	req := importWrite(t, dir, "requirements.txt", "requests\n--index-url https://example.com/simple\n")
	out := mustImport(t, req, "--project", "api")
	if !strings.Contains(out, "name: api-pypi-requests") {
		t.Errorf("out: %s", out)
	}
}

// Criterion: output, warnings and -v.
func TestImportStdoutStderr(t *testing.T) {
	isolate(t)
	dir := t.TempDir()
	req := importWrite(t, dir, "requirements.txt", "requests==2.31.0\n-e .\nflask\n")
	out, errOut, err := runCLI(t, "import", req, "--project", "api", "-v", "--exclude", "fl*")
	if err != nil {
		t.Fatal(err)
	}
	if !strings.HasPrefix(out, "# Generated by angelia import from "+req+". Changes are overwritten by the next import.\nversion: 1\n") {
		t.Errorf("stdout: %s", out)
	}
	if strings.Contains(out, "warning") || strings.Contains(out, "->") {
		t.Errorf("stdout carries stderr text: %s", out)
	}
	for _, want := range []string{
		"warning: " + req + ":2: skipped -e .: editable requirements are not registry dependencies\n",
		"requests 2.31.0 -> api-pypi-requests\n",
		"flask -> (excluded by --exclude)\n",
	} {
		if !strings.Contains(errOut, want) {
			t.Errorf("stderr lacks %q:\n%s", want, errOut)
		}
	}
}

// Criterion: --strict turns a skip into an error and prints no watch file.
func TestImportStrict(t *testing.T) {
	isolate(t)
	dir := t.TempDir()
	req := importWrite(t, dir, "requirements.txt", "requests\n-e .\n")
	out, _, err := runCLI(t, "import", req, "--project", "api", "--strict")
	if err == nil || !strings.Contains(err.Error(), "--strict: 1 skipped") || out != "" {
		t.Errorf("err = %v, stdout = %q", err, out)
	}
	// An ignored index option is not a skip.
	idx := importWrite(t, dir, "requirements-idx.txt", "requests\n-i https://example.com/simple\n")
	if _, _, err := runCLI(t, "import", idx, "--project", "api", "--strict"); err != nil {
		t.Errorf("strict with an index line: %v", err)
	}
}

// Criterion: usage errors.
func TestImportUsageErrors(t *testing.T) {
	isolate(t)
	dir := t.TempDir()
	req := importWrite(t, dir, "requirements.txt", "requests\n")
	other := importWrite(t, dir, "deps.lst", "requests\n")
	bad := importWrite(t, dir, "bad.yaml", "bogus: 1\n")
	for _, tc := range []struct {
		args []string
		want string
	}{
		{[]string{"import", req}, `required flag(s) "project" not set`},
		{[]string{"import", "--project", "api"}, "name at least one manifest file"},
		{[]string{"import", req, "--project", "Api"}, "--project"},
		{[]string{"import", other, "--project", "api"}, "cannot tell the format"},
		{[]string{"import", other, "--project", "api", "--format", "yaml"}, `--format "yaml"`},
		{[]string{"import", req, "--project", "api", "-l", "novalue"}, "want key=value"},
		{[]string{"import", req, "--project", "api", "-l", "bad key=x"}, "labels"},
		{[]string{"import", req, "--project", "api", "--include", "all"}, "--include"},
		{[]string{"import", req, "--project", "api", "--source", "pypi"}, "KIND=NAME"},
		{[]string{"import", req, "--project", "api", "--interval", "1s"}, "--interval"},
		{[]string{"import", req, "--project", "api", "--policy", bad}, "bad.yaml: line 1: bogus: unknown key"},
		{[]string{"import", req, "--project", "api", "--policy", filepath.Join(dir, "missing.yaml")}, "read "},
		{[]string{"import", filepath.Join(dir, "requirements-missing.txt"), "--project", "api"}, "read "},
	} {
		out, _, err := runCLI(t, tc.args...)
		if err == nil || !strings.Contains(err.Error(), tc.want) || out != "" {
			t.Errorf("%v: err = %v, stdout = %q, want %q", tc.args[1:], err, out, tc.want)
		}
	}
}

